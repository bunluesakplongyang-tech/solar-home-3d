#!/usr/bin/env python3
"""Build dist/solar-home-3d.js (Lovelace card) from src/solar-home-3d.html."""
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
html = (root / "src" / "solar-home-3d.html").read_text(encoding="utf8")
ver = re.search(r"APP_VERSION='([^']+)'", html).group(1)
card = """/* Solar Home 3D v%(ver)s - Lovelace card (generated by tools/build.py) */
const SH3D_HTML = %(html)s;
class SolarHome3DCard extends HTMLElement {
  setConfig(config) {
    this._config = Object.assign({ height: 640 }, config || {});
    if (this._frame) this._frame.style.height = this._h();
  }
  _h() { const h = this._config.height; return typeof h === "number" ? h + "px" : String(h); }
  set hass(hass) {
    window.__sh3d_hass = hass;               // the embedded page reads HA auth from here
    if (this._frame) return;
    this.attachShadow({ mode: "open" });
    const frame = document.createElement("iframe");
    frame.style.cssText = "width:100%%;border:0;display:block;border-radius:var(--ha-card-border-radius,12px);background:#0b1220";
    frame.style.height = this._h();
    frame.setAttribute("allow", "fullscreen");
    frame.srcdoc = SH3D_HTML;
    this.shadowRoot.appendChild(frame);
    this._frame = frame;
  }
  getCardSize() { return 10; }
  static getStubConfig() { return { height: 640 }; }
}
customElements.define("solar-home-3d", SolarHome3DCard);
window.customCards = window.customCards || [];
window.customCards.push({ type: "solar-home-3d", name: "Solar Home 3D", description: "Animated 3D solar house dashboard - pick your own inverter/battery/grid/EV entities.", preview: false });
console.info("%%c SOLAR-HOME-3D %%c v%(ver)s ", "color:#fff;background:#2e7d32;font-weight:700", "color:#2e7d32");
""" % {"ver": ver, "html": json.dumps(html, ensure_ascii=False).replace("</script", "<\\/script")}
(root / "dist").mkdir(exist_ok=True)
(root / "dist" / "solar-home-3d.js").write_text(card, encoding="utf8")
print("built dist/solar-home-3d.js", ver, len(card) // 1024, "KB")
